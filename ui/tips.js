const tk = (el, key) => { el.dataset.tipk = key; return el; };
const ctlText = (el) => (el.tagName === "BUTTON" ? el.textContent.replace(/\s+/g, " ").trim() : "");
/* 조작 하나의 설명 키 · 글 */
function tipEntry(el) {
  let key = el.dataset.tipk || ctlText(el);
  if (!key) return null;
  if (key.startsWith("cfg:")) {
    const it = TIP_CFG[key.slice(4)];
    return it ? { title: it.label, t: it.desc, hint: it.hint } : { t: "설정 " + key.slice(4) };
  }
  let e = TIPS[key];
  if (e == null) {                                               // 이름에 숫자 · 꼭짓점이 들어가는 버튼
    if (/^[\d.]+$/.test(key)) e = TIPS["jog.step"];
    else if (/^[A-D] 등록$/.test(key)) e = TIPS["corner.set"];
    else if (/예상 위치로 이동$/.test(key)) e = TIPS["corner.guess"];
  }
  if (typeof e === "function") e = e(el);
  if (e == null) return null;
  return typeof e === "string" ? { t: e } : e;
}
/* 꺼진 까닭: el._why → 같은 줄(부모 · 조부모)의 .why 글 → 기본 글 */
function whyOf(el) {
  if (el._why) return el._why;
  for (let p = el.parentElement, k = 0; p && k < 3; p = p.parentElement, k++) {
    for (const w of p.querySelectorAll(":scope > .why")) { const t = w.textContent.trim(); if (t && !w.classList.contains("hidden")) return t; }
  }
  return "지금 사용 불가";
}
/* 말풍선 내용(core.js showTip 이 쓴다): {title, text, hint} */
function tipOf(el) {
  if (el._tip) { const c = typeof el._tip === "function" ? el._tip() : el._tip; return typeof c === "string" ? { text: c } : c; }
  const e = tipEntry(el);
  if (!e) return null;
  const title = el._title || e.title || ctlText(el) || "";
  let text = e.t || "";
  if (e.m) text += "\n움직임: " + e.m;
  if (el.disabled) text += "\n꺼짐 · " + whyOf(el);
  return { title, text, hint: e.hint || "" };
}
const isCtl = (el) => el.tagName === "BUTTON" || el.tagName === "SELECT" || (el.tagName === "INPUT" && el.type !== "file" && el.type !== "hidden");
const hasTip = (el) => !!(el._tip || (el.dataset && (el.dataset.tipk || (isCtl(el) && tipEntry(el)))));

/* 개발 중 점검: 설명이 없는 조작을 콘솔에 한 번씩 경고(화면 동작에는 영향 없음) */
const tipWarned = new Set();
function tipAudit(root) {
  for (const el of (root || document).querySelectorAll("button, select, input")) {
    if (!isCtl(el) || hasTip(el)) continue;
    const key = (el.dataset.tipk || ctlText(el) || el.tagName + (el.type ? ":" + el.type : "") + (el.placeholder ? ":" + el.placeholder : "")) + " @" + (el.closest("[id]") || {}).id;
    if (tipWarned.has(key)) continue;
    tipWarned.add(key);
    console.warn("말풍선 설명 없음 · " + key);
  }
}
setInterval(() => tipAudit(), 5000);
